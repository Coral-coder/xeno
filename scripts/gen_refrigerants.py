def sat(fluid, t_k, q):
    try:
        return CP.PropsSI("P", "T", t_k, "Q", q, fluid) / 1000.0
    except Exception:
        return None

def table(fluid):
    tmin_c, tmax_c = -60, 75
    try:
        tc = CP.PropsSI("Tcrit", fluid) - 273.15
        tmax_c = min(tmax_c, int(tc) - 1)
    except Exception:
        pass
    temps, bub, dew = [], [], []
    for t in range(tmin_c, tmax_c + 1):
        b = sat(fluid, t + 273.15, 0)
        d = sat(fluid, t + 273.15, 1)
        if b is None or d is None or b <= 0 or d <= 0:
            if temps:
                break
            continue
        temps.append(t); bub.append(b); dew.append(d)
    return temps, bub, dew

def fmt(values):
    return ", ".join("%.3f" % v for v in values)

out = []
out.append("// Generated by scripts/gen_refrigerants.py from CoolProp %s. Do not edit by hand." % CP.get_global_param_string("version"))
out.append("// Saturation pressures in kPa absolute, one entry per °C starting at `startC`.")
out.append("")
out.append("enum RefrigerantData {")
out.append("    static let all: [RefrigerantTable] = [")
for name, fluid, safety, oil, use in REFRIGERANTS:
    temps, bub, dew = table(fluid)
    if len(temps) < 20:
        print("skipping", name, len(temps), file=sys.stderr)
        continue
    # contiguous check
    assert temps == list(range(temps[0], temps[0] + len(temps))), name
    out.append("        RefrigerantTable(")
    out.append('            name: "%s", safetyClass: "%s", oil: "%s", use: "%s", startC: %d,' % (name, safety, oil, use, temps[0]))
    out.append("            bubbleKPa: [%s]," % fmt(bub))
    out.append("            dewKPa: [%s]" % fmt(dew))
    out.append("        ),")
    glide = max(abs(b - d) for b, d in zip(bub, dew))
    print("%-12s %4d..%3d C  max dP %.1f kPa" % (name, temps[0], temps[-1], glide), file=sys.stderr)
out.append("    ]")
out.append("}")
out.append("")
sys.stdout.write("\n".join(out))
